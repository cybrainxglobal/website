export const ui = (lang) => UI[lang] || UI.en;

export const playUrl = (pkg) => `https://play.google.com/store/apps/details?id=${encodeURIComponent(pkg)}`;

/** Per-app colors for dark (landing) and light (legal) backgrounds. */
export function theme(app) {
  const [c1, c2] = app.colors;
  return {
    c1,
    c2,
    rgb: hexToRgb(c1).join(', '),
    onDark: readable(c1, '#0f172a', '#ffffff'),
    onLight: readable(c1, '#fffaf4', '#000000'),
    softLight: mix(readable(c1, '#fffaf4', '#000000'), '#ffffff', 0.88),
  };
}

function iconTile(app, cls, prefix = '') {
  return app.image
    ? `<div class="${cls}"><img src="${esc(prefix + app.image)}" alt="" loading="lazy"></div>`
    : `<div class="${cls}"><i class="${esc(app.icon)}" aria-hidden="true"></i></div>`;
}

