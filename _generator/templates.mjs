/**
 * `doc` comes from legal.mjs. The date and year are left as placeholders so
 * the caller can hash the content and keep the "Last updated" date stable
 * until the text itself changes.
 */
export function legalPage(app, site, doc, kind) {
  const u = ui(app.lang);
  const th = theme(app);
  const name = esc(app.name);
  const file = kind === 'privacy' ? 'privacy-policy.html' : 'terms-of-use.html';
  const deletion = `../data-deletion-request.html?app=${encodeURIComponent(app.slug)}`;
  const current = (f) => (f === file ? ' aria-current="page"' : '');
  const plainLede = doc.lede.replace(/<[^>]+>/g, '');

  return `<!DOCTYPE html>
<html lang="${app.lang === 'pt' ? 'pt-BR' : 'en'}">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    ${MARKER}
    <meta name="content-hash" content="%%HASH%%">
    <!-- Generated from _apps/${esc(app.slug)}.json — edit that file, not this one. -->
    <title>${name} ${esc(doc.title)}</title>
    <meta name="description" content="${esc(plainLede)}" />
    <link rel="canonical" href="${esc(`${site.baseUrl}/${app.slug}/${file}`)}" />
    <link rel="stylesheet" href="../app-pages.css" />
    <style>:root { --accent: ${th.onLight}; --accent-soft: ${th.softLight}; }</style>
  </head>
  <body class="legal-doc">
    <header class="topbar">
      <a class="brand" href="../index.html">${esc(site.company)}</a>
      <nav aria-label="${name}">
        <a href="index.html">${name}</a>
        <a href="privacy-policy.html"${current('privacy-policy.html')}>${u.privacy}</a>
        <a href="terms-of-use.html"${current('terms-of-use.html')}>${u.terms}</a>
      </nav>
    </header>

    <main class="container">
      <section class="hero">
        <span class="pill">${esc(doc.pill)}</span>
        <h1>${name}</h1>
        <p class="lede">
          ${doc.lede}
        </p>
        <p class="meta" data-updated="%%UPDATED_ISO%%">
          ${u.updated}: %%UPDATED%%
        </p>

        <nav class="toc" aria-label="${u.toc}">
${doc.sections.map((s) => `          <a href="#${esc(s.id)}">${esc(s.title)}</a>`).join('\n')}
        </nav>
      </section>
${doc.sections
  .map(
    (s) => `
      <section class="section" id="${esc(s.id)}">
        <h2>${esc(s.title)}</h2>
${indent(s.html, 8)}
      </section>`,
  )
  .join('\n')}
    </main>

    <footer class="site-footer">
      <div class="footer-links">
        <a href="index.html">${name}</a>
        <a href="privacy-policy.html"${current('privacy-policy.html')}>${u.privacy}</a>
        <a href="terms-of-use.html"${current('terms-of-use.html')}>${u.terms}</a>
        <a href="${esc(deletion)}">${u.deletion}</a>
        <a href="../index.html#apps">${u.allApps}</a>
      </div>
      <p>&copy; %%YEAR%% ${esc(site.company)}. ${u.rights}</p>
    </footer>
  </body>
</html>
`;
}

function indent(html, spaces) {
  const pad = ' '.repeat(spaces);
  return html
    .split('\n')
    .filter((line) => line.trim())
    .map((line) => pad + line)
    .join('\n');
}

// ─── Home page card ─────────────────────────────────────────────────────────

export function homeCard(app) {
  const th = theme(app);
  const icon = app.image
    ? `<img src="${esc(`${app.slug}/${app.image}`)}" alt="" loading="lazy" style="width:100%;height:100%;object-fit:cover;border-radius:inherit;">`
    : `<i class="${esc(app.icon)}"></i>`;
  const tags = (app.tags || [])
    .slice(0, 2)
    .map((tag) => `<span class="tag"><i class="${esc(tag.icon)}"></i> ${esc(tag.label)}</span>`)
    .join('\n                        ');
  return `            <!-- ${esc(app.name)} (generated from _apps/${esc(app.slug)}.json) -->
            <a href="${esc(app.slug)}/index.html" class="card reveal">
                <div class="card-glow"
                    style="background: radial-gradient(circle, rgba(${th.rgb},0.16) 0%, transparent 70%);"></div>
                <div class="card-icon" style="background: linear-gradient(135deg, ${th.c1}, ${th.c2});">
                    ${icon}
                </div>
                <div class="card-content">
                    <h3>${esc(app.name)}</h3>
                    <p>${esc(app.tagline)}</p>
                    <div class="card-tags">
                        ${tags}
                    </div>
                    <span class="card-arrow"><i class="fa-solid fa-arrow-right"></i></span>
                </div>
            </a>
`;
}

